export const dictionaries = { en, ar } as const;
export const supportedLocales = ['en', 'ar'] as const;
export type RestaurantLocale = (typeof supportedLocales)[number];
export type LocaleDirection = 'ltr' | 'rtl';
export type TranslationParams = Record<string, string | number>;

export function normalizeLocale(value: string | null | undefined): RestaurantLocale {
  return value === 'ar' ? 'ar' : 'en';
}

export function localeDirection(locale: RestaurantLocale): LocaleDirection {
  return locale === 'ar' ? 'rtl' : 'ltr';
}

export function nextLocale(locale: RestaurantLocale): RestaurantLocale {
  return locale === 'en' ? 'ar' : 'en';
}

export function translate(
  locale: RestaurantLocale,
  key: TranslationKey,
  params: TranslationParams = {},
): string {
  const template: string = dictionaries[locale][key];
  return template.replace(/\{\{(\w+)\}\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}
